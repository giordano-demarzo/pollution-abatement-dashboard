class BREFHierarchyProcessor:
    def __init__(self, input_dir, output_dir="./processed_data"):
        """
        Process BREF files to extract hierarchical structure.

        Args:
            input_dir (str): Directory containing BREF section files
            output_dir (str): Directory to save processed data
        """
        self.input_dir = input_dir
        self.output_dir = output_dir
        self.sections = {}  # {section_id: {'title': title, 'content': content}}
        self.section_hierarchy = defaultdict(list)  # {chapter: [section_ids]}
        self.bref_codes = set()  # Set of unique BREF codes

        # Create output directory
        os.makedirs(output_dir, exist_ok=True)

    def parse_files(self):
        """Parse all BREF files and extract section information"""
        print("Parsing BREF files...")
        files = []

        # Walk through the directory and collect all .txt files
        for root, _, filenames in os.walk(self.input_dir):
            for filename in filenames:
                if filename.endswith('.txt'):
                    files.append(os.path.join(root, filename))

        print(f"Found {len(files)} BREF files")

        for file_path in tqdm(files):
            self._process_file(file_path)

        print(f"Processed {len(self.sections)} sections across {len(self.bref_codes)} BREF documents")

    def _process_file(self, file_path):
        """
        Process a single BREF section file.

        Args:
            file_path (str): Path to the section file
        """
        # Extract BREF code from the path
        path_parts = file_path.split(os.sep)
        if len(path_parts) > 1:
            bref_code = path_parts[-2]  # Assume the parent folder is the BREF code
            self.bref_codes.add(bref_code)
        else:
            bref_code = "UNKNOWN"

        # Extract section ID and title from filename
        filename = os.path.basename(file_path)
        section_id, title = self._parse_filename(filename)

        if not section_id:
            return  # Skip files without valid section IDs

        # Create a full section ID with BREF code
        full_section_id = f"{bref_code}:::{section_id}"

        # Read file content
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                content = f.read()
        except UnicodeDecodeError:
            try:
                with open(file_path, 'r', encoding='latin-1') as f:
                    content = f.read()
            except Exception as e:
                print(f"Error reading {file_path}: {e}")
                return

        # Store section info
        self.sections[full_section_id] = {
            'title': title,
            'content': content,
            'file_path': file_path,
            'bref_code': bref_code
        }

        # Add to hierarchy
        if '.' in section_id:
            chapter = section_id.split('.')[0]
        else:
            chapter = section_id

        chapter_key = f"{bref_code}:::{chapter}"
        self.section_hierarchy[chapter_key].append(full_section_id)

    def _parse_filename(self, filename):
        """
        Parse section ID and title from filename.

        Args:
            filename (str): Filename of BREF section

        Returns:
            tuple: (section_id, title)
        """
        # Remove file extension
        base_name = os.path.splitext(filename)[0]

        # Handle special cases for metadata files
        if base_name.startswith('_'):
            return None, base_name[1:]

        # Extract section ID and title
        match = re.match(r'^(\d+(?:\.\d+)*(?:\.\d+)*(?:\.\d+)*)_(.+)$', base_name)
        if match:
            section_id = match.group(1)
            title = match.group(2).replace('_', ' ')
            return section_id, title

        # Handle chapter files like "1_GENERAL INFORMATION.txt"
        match = re.match(r'^(\d+)_(.+)$', base_name)
        if match:
            section_id = match.group(1)
            title = match.group(2).replace('_', ' ')
            return section_id, title

        return None, base_name

    def build_hierarchy(self):
        """Build the hierarchical structure for the dashboard"""
        print("Building hierarchical structure...")

        # Group sections by BREF code
        bref_structures = {}

        for bref_code in self.bref_codes:
            # Find all sections for this BREF
            bref_sections = {k: v for k, v in self.sections.items() if v['bref_code'] == bref_code}

            # Start with chapters
            chapter_sections = {k: v for k, v in bref_sections.items() if '.' not in k.split(':::')[1]}

            # Sort chapters
            sorted_chapters = sorted(chapter_sections.keys(),
                                      key=lambda x: int(x.split(':::')[1]) if x.split(':::')[1].isdigit() else float('inf'))

            # Create hierarchical structure
            bref_hierarchy = []

            for chapter_id in sorted_chapters:
                chapter_obj = {
                    'id': chapter_id,
                    'name': chapter_sections[chapter_id]['title'],
                    'children': []
                }

                # Get all subsections for this chapter
                chapter_num = chapter_id.split(':::')[1]
                subsections = {k: v for k, v in bref_sections.items()
                               if k != chapter_id and k.split(':::')[1].startswith(f"{chapter_num}.")}

                # Add subsections recursively
                self._add_children(chapter_obj, subsections)

                bref_hierarchy.append(chapter_obj)

            bref_structures[bref_code] = bref_hierarchy

        # Save hierarchical structure to JSON
        output_path = os.path.join(self.output_dir, "bref_hierarchy.json")
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(bref_structures, f, indent=2)

        print(f"Saved hierarchical structure to {output_path}")
        return bref_structures

    def _add_children(self, parent, sections):
        """
        Recursively add children to parent section.

        Args:
            parent (dict): Parent section object
            sections (dict): Dictionary of sections to process
        """
        parent_id = parent['id']
        parent_path = parent_id.split(':::')[1]

        # Find direct children (one level deeper)
        direct_children = {}
        for section_id, section in sections.items():
            section_path = section_id.split(':::')[1]

            # Check if this is a direct child
            if section_path.count('.') == parent_path.count('.') + 1 and section_path.startswith(f"{parent_path}."):
                direct_children[section_id] = section

        # Sort children
        sorted_children = sorted(direct_children.keys(),
                                 key=lambda x: [int(p) if p.isdigit() else 0 for p in x.split(':::')[1].split('.')])

        # Add each child and its children
        for child_id in sorted_children:
            child_obj = {
                'id': child_id,
                'name': direct_children[child_id]['title'],
                'children': []
            }

            # Recursively add children to this child
            self._add_children(child_obj, sections)

            # Add to parent's children
            parent['children'].append(child_obj)

    def process(self):
        """Run the full processing pipeline"""
        self.parse_files()
        hierarchy = self.build_hierarchy()
        return hierarchy

