    plt.xlabel('Number of Patents')
    plt.title('Top 30 Pollutants by Patent Count')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, "pollutant_patent_counts.png"), dpi=300)
    plt.close()

    print(f"Visualizations saved to {output_dir}")
    return output_dir

