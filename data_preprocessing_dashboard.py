    top_pollutants = [p[0] for p in sorted_pollutants[:2]]  # Take 2 most common
    mid_pollutants = [p[0] for p in sorted_pollutants[len(sorted_pollutants)//2:len(sorted_pollutants)//2+1]]  # Take 1 from middle
    bottom_pollutants = [p[0] for p in reversed(sorted_pollutants) if p[1] > 0][:1]  # Take 1 from bottom (with patents)

