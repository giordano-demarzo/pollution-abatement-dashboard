    print("\nPreparing dashboard data...")
    patent_data = {}

    # Track filenames to ensure consistent cleaning
    pollutant_to_filename = {}

    # Function to clean pollutant names for filenames
    def clean_for_filename(pollutant):
        # Replace any non-alphanumeric chars with underscores
        cleaned = re.sub(r'[^a-zA-Z0-9_\-.]', '_', pollutant)
        # Replace multiple underscores with one
        cleaned = re.sub(r'_+', '_', cleaned)
        # Remove trailing underscores
        cleaned = cleaned.strip('_')
        return cleaned

    # For each pollutant, process ALL patents (filtered by relevance)
    for pollutant in unique_pollutants:
        pollutant_patents = integrated_df[integrated_df['pollutant'] == pollutant]

        # Sort by relevance score for easier browsing
        pollutant_patents = pollutant_patents.sort_values('relevance_score', ascending=False)

        # Convert to the format expected by the dashboard
        patents_list = []
        for _, patent in pollutant_patents.iterrows():
            patents_list.append({
                'id': str(patent['APPLN_ID']),
                'title': str(patent['APPLN_TITLE'])[:100],  # Limit title length
                'score': float(patent['relevance_score']),
                'x': float(patent['x']),
                'y': float(patent['y']),
                'abstract': f"Patent ID {patent['APPLN_ID']} from year {patent['APPLN_YR']} related to {pollutant} abatement technology."
            })

        print(f"Pollutant {pollutant}: {len(patents_list)} patents")
        patent_data[pollutant] = patents_list

        # Create consistent filename for this pollutant
        filename = clean_for_filename(pollutant)
        pollutant_to_filename[pollutant] = filename

    # Create the final data structure
    dashboard_data = {
        'sdgs': sdg_data,
        'pollutants': list(unique_pollutants),
        'sdgImpact': sdg_impact_data,
        'patents': patent_data,
        'brefHierarchy': bref_hierarchy
    }

    # Save metadata about the dataset
    metadata = {
        "relevance_threshold": relevance_threshold,
        "creation_date": pd.Timestamp.now().strftime("%Y-%m-%d %H:%M:%S"),
        "total_patents": integrated_df['APPLN_ID'].nunique(),
        "total_pollutants": len(unique_pollutants),
        "total_patent_pollutant_pairs": len(integrated_df),
        "scoring_method": "max_score_among_matching_bref_sections"
    }

    with open(os.path.join(output_dir, "metadata.json"), 'w') as f:
        json.dump(metadata, f, indent=2)

    # 7. Save to JSON files
    print("Saving dashboard data...")

    # Main dashboard data
    output_path = os.path.join(output_dir, "dashboard_data.json")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(dashboard_data, f, indent=2)

    # Save individual components (except patents which might be large)
    for key, data in dashboard_data.items():
        if key != 'patents':
            component_path = os.path.join(output_dir, f"{key}.json")
            with open(component_path, 'w', encoding='utf-8') as f:
                json.dump(data, f, indent=2)

    # Save patents by pollutant
    patents_dir = os.path.join(output_dir, "patents")
    os.makedirs(patents_dir, exist_ok=True)

    # Save a mapping file for pollutant filenames
    with open(os.path.join(output_dir, "pollutant_filenames.json"), 'w') as f:
        json.dump(pollutant_to_filename, f, indent=2)

    for pollutant, patents in dashboard_data['patents'].items():
        # Use our consistent filename cleaning function
        filename = pollutant_to_filename[pollutant]
        pollutant_path = os.path.join(patents_dir, f"{filename}.json")

        with open(pollutant_path, 'w', encoding='utf-8') as f:
            json.dump(patents, f, indent=2)

    print("Data integration complete! Dashboard data is ready for use.")
    return dashboard_data, pollutant_to_filename

