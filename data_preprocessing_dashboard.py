    plt.title('UMAP Projection of Patents by Pollutant', fontsize=16)
    plt.xlabel('UMAP Dimension 1', fontsize=12)
    plt.ylabel('UMAP Dimension 2', fontsize=12)

    # Add the legend
    plt.legend(handles=legend_handles, loc='upper right')

    plt.grid(alpha=0.3)
    plt.tight_layout()

    # Save the combined figure
    plt.savefig(os.path.join(output_dir, "umap_combined_pollutants.png"), dpi=300)
